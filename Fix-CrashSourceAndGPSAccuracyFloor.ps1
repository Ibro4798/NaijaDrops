<#
  Fix-CrashSourceAndGPSAccuracyFloor.ps1
  Compatible with Windows PowerShell 5.1 (no PS7-only syntax used).

  Full, backed-up REPLACEMENT of 4 files. Each file's exact content is
  embedded as base64 of the RAW FILE BYTES and written back byte-for-byte.

  This addresses TWO issues found by re-reading everything mounted in
  layout.js and everything the last GPS change touched, after the crash
  screen kept appearing and pickup locations came back wrong.

  ISSUE 1 - A SECOND, MORE FREQUENT CAUSE OF THE CRASH SCREEN:

  The previous fix (SilentErrorBoundary around the two notification
  listeners) is still correct and still in place - confirmed unchanged.
  But it wasn't the only thing capable of crashing the whole app the same
  way. ThemeProvider.jsx is ALSO mounted in layout.js as a sibling of
  {children}, outside the tree app/error.jsx protects - and it was calling
  localStorage.getItem/setItem with no try/catch, in a useEffect that runs
  on EVERY page load for EVERY visitor. Unlike the notification listeners
  (narrow failure conditions), storage access throwing is not rare: in-app
  browsers (WhatsApp's, Instagram's - plausible here, since delivery links
  get shared over WhatsApp) and privacy-hardened browsers are known to
  restrict or block it outright. That combination - a common crash trigger
  sitting somewhere totally unprotected - is almost certainly why the
  crash screen was showing up "a bit too much." Both localStorage calls now
  go through a small safeGetItem/safeSetItem wrapper that falls back to the
  dark default instead of ever throwing.

  ISSUE 2 - GPS "UNBLOCK ON FIRST FIX" HAD NO ACCURACY FLOOR:

  The change that let a customer move to step 2 as soon as ANY GPS reading
  arrived had a real gap: geolocation.js's coarse approximate fetch
  (enableHighAccuracy:false, used to paint something on screen fast) has no
  accuracy ceiling of its own. On sparse cell-tower coverage it can be off
  by hundreds of meters to a few kilometers - so a customer could get
  unblocked onto a pickup pin reverse-geocoded to the wrong neighborhood
  entirely, with no guarantee the silent background refinement finished
  correcting it before they submitted the order.

  Fix: every reading geolocation.js hands back now carries a `usable` flag
  - true once accuracy is <=150m, or once 8 seconds have passed with
  nothing better (so a genuinely poor-signal device still doesn't hang
  forever). send-package/step-1 and MapModal.jsx now only commit to /
  reverse-geocode a reading once it's `usable` - earlier, rougher readings
  still move the live pin for visual feedback, they're just never locked
  in as the actual answer.

  Run from the ROOT of your local repo clone:
      powershell -ExecutionPolicy Bypass -File .\Fix-CrashSourceAndGPSAccuracyFloor.ps1
#>

$ErrorActionPreference = "Stop"
$root = Get-Location
$backupDir = Join-Path $root ".fix-backup-crashsource"
if (-not (Test-Path -LiteralPath $backupDir)) { New-Item -ItemType Directory -Path $backupDir | Out-Null }

function Get-FullPath($rel) { return Join-Path $root $rel }

function Backup-Path($full) {
    if (Test-Path -LiteralPath $full) {
        $rel = $full.Substring($root.Path.Length).TrimStart('\','/')
        $dest = Join-Path $backupDir $rel
        $destParent = Split-Path $dest -Parent
        if (-not (Test-Path -LiteralPath $destParent)) { New-Item -ItemType Directory -Path $destParent -Force | Out-Null }
        Copy-Item -LiteralPath $full -Destination $dest -Force
    }
}

function Write-FullFile($relPath, $base64Content, $label) {
    $full = Get-FullPath $relPath
    if (-not (Test-Path -LiteralPath $full)) {
        Write-Host "  SKIP (not found): $relPath - is this the right repo root?" -ForegroundColor Yellow
        return
    }
    Backup-Path $full
    $bytes = [System.Convert]::FromBase64String($base64Content)
    [System.IO.File]::WriteAllBytes($full, $bytes)
    Write-Host "  REPLACED: $label" -ForegroundColor Green
}

if (-not (Test-Path -LiteralPath (Get-FullPath "src\app"))) {
    Write-Host "ERROR: src\app not found. Run this script from the repo root." -ForegroundColor Red
    exit 1
}

