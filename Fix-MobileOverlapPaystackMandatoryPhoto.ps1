<#
  Fix-MobileOverlapPaystackMandatoryPhoto.ps1
  Compatible with Windows PowerShell 5.1 (no PS7-only syntax used).

  Full, backed-up REPLACEMENT of the 5 files below (same approach as
  Fix-VendorHistoryPaymentRadiusLocation.ps1) - each file's exact new
  content is embedded as base64 of the RAW ORIGINAL BYTES (BOM included
  where the file already had one) and written back byte-for-byte, so
  there's no text re-encoding step to go wrong.

  What this fixes:

  1. "PAY NOW" BUTTON NOT WORKING
     src\utils\paystack.js used to just console.warn() when
     NEXT_PUBLIC_PAYSTACK_PUBLIC_KEY was missing or a placeholder, and then
     called PaystackPop.setup() anyway with a broken key - Paystack's inline
     widget fails completely silently in that case (no popup, no visible
     error), which is exactly why "Pay Now" looked like it did nothing.
     It now stops before opening the iframe and reports a real error back
     to the page, which src\app\payment\page.jsx now displays visibly.

     IMPORTANT - this script can only fix the CODE side of this. To
     actually test the flow you still need to set your Paystack TEST keys:
       - NEXT_PUBLIC_PAYSTACK_PUBLIC_KEY = pk_test_xxxxx  (safe to expose -
         it's a publishable key by design)
       - PAYSTACK_SECRET_KEY = sk_test_xxxxx  (server-only - never expose
         this one client-side or commit it to git)
     Add both to .env.local for local dev, AND to Vercel -> Settings ->
     Environment Variables for Production - then redeploy. NEXT_PUBLIC_
     vars are baked in at build time, so a redeploy is required after
     adding/changing them, a plain restart is not enough.

  2. MOBILE LAYOUT OVERLAP
     Two spots hardened for narrow phones (360-390px):
       - The rider incoming-job card's price (text-5xl) sat right next to a
         fixed 48px reject button with no min-w-0/shrink handling and
         fairly large p-8 padding - a long price had nowhere to go but
         crowd the button. Now responsive (text-4xl on small screens,
         text-5xl from sm: up), padding drops to p-6 on small screens, and
         the price container has min-w-0 + truncate as a safety net.
       - The tracking page's Status/chat-button header row had no min-w-0
         on the text side, so a longer status label could push against the
         48px chat button instead of truncating cleanly.

  3. PACKAGE PHOTO NOW REQUIRED
     src\app\send-package\step-2\page.jsx previously let a rider be
     dispatched a job with zero photo - the Continue button never checked
     for one. It's now required: Continue stays disabled until a photo has
     actually finished uploading (not just been selected), the label and
     empty-state copy now say "required" instead of "optional," and a
     failed upload clears the preview and shows a real inline error instead
     of the old "you can still continue without it" message.

  Run from the ROOT of your local repo clone:
      powershell -ExecutionPolicy Bypass -File .\Fix-MobileOverlapPaystackMandatoryPhoto.ps1
#>

$ErrorActionPreference = "Stop"
$root = Get-Location
$backupDir = Join-Path $root ".fix-backup-batch3"
if (-not (Test-Path -LiteralPath $backupDir)) { New-Item -ItemType Directory -Path $backupDir | Out-Null }

function Get-FullPath($rel) { return Join-Path $root $rel }

function Backup-Path($full) {
    if (Test-Path -LiteralPath $full) {
        $rel = $full.Substring($root.Path.Length).TrimStart('\','/')
        $dest = Join-Path $backupDir $rel
        $destParent = Split-Path $dest -Parent
        if (-not (Test-Path -LiteralPath $destParent)) { New-Item -ItemType Directory -Path $destParent -Force | Out-Null }
        Copy-Item -LiteralPath $full -Destination $dest -Force
    }
}

function Write-FullFile($relPath, $base64Content, $label) {
    $full = Get-FullPath $relPath
    if (-not (Test-Path -LiteralPath $full)) {
        Write-Host "  SKIP (not found): $relPath - is this the right repo root?" -ForegroundColor Yellow
        return
    }
    Backup-Path $full
    $bytes = [System.Convert]::FromBase64String($base64Content)
    [System.IO.File]::WriteAllBytes($full, $bytes)
    Write-Host "  REPLACED: $label" -ForegroundColor Green
}

