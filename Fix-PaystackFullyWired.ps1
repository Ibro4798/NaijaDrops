<#
  Fix-PaystackFullyWired.ps1
  Compatible with Windows PowerShell 5.1 (no PS7-only syntax used).

  Full, backed-up REPLACEMENT of src\app\payment\page.jsx - same approach
  as the previous Fix-*.ps1 scripts. The file's exact new content is
  embedded as base64 of the RAW ORIGINAL BYTES (BOM included) and written
  back byte-for-byte.

  WHY "PAY NOW" WASN'T FULLY WORKING - two real bugs found:

  1. THE "OPAY" BUTTON WAS ENTIRELY FAKE, AND WOULD BREAK ONCE REAL KEYS
     WERE ADDED. The payment page had two options: a real Paystack path,
     and a separate "OPay Digital" button with a fake QR-code screen that
     just simulated success client-side - no real payment was ever
     collected through it. It worked by faking a Paystack-style reference
     (ND_OPAY_...) and sending it to /api/verify-payment, which has a
     dev-only fallback that marks orders paid when PAYSTACK_SECRET_KEY
     isn't configured. The moment a REAL secret key is set (which is the
     whole point of "fully wiring this up"), that same call instead tries
     to verify the fake reference against Paystack's real API - which
     correctly rejects it as a transaction that never happened. So this
     button would go from "fake-successful" in dev to permanently broken
     the moment real payments were turned on. It's been removed entirely.
     Paystack's own real checkout already supports card, bank transfer,
     USSD, and mobile money as channels within one verified transaction,
     so nothing is lost - there's now a single, real, fully verified
     payment path instead of a confusing choice between a real one and a
     fake one.

  2. THE PAYSTACK SCRIPT LOAD WAS FIRE-AND-FORGET. The page called
     loadPaystackScript() on mount but never tracked whether it actually
     finished before the "Pay Now" button could be clicked - on a slower
     connection, clicking fast enough could hit initializePaystack() before
     window.PaystackPop existed, showing "gateway failed to load" even
     though it would have worked a moment later. The button now reflects
     real load state: it shows "Loading Secure Gateway..." and stays
     disabled until Paystack's SDK actually confirms ready, with a genuine
     error and an 8-second timeout safety net if the script never loads at
     all (e.g. blocked by an ad/tracker blocker).

  STILL REQUIRED ON YOUR END - this script only fixes the code. To actually
  test real payments end-to-end you still need, in both .env.local and
  Vercel -> Settings -> Environment Variables (Production, then redeploy
  since NEXT_PUBLIC_ vars are baked in at build time):
    - NEXT_PUBLIC_PAYSTACK_PUBLIC_KEY = pk_test_xxxxx  (safe to share - it's
      a publishable key by design)
    - PAYSTACK_SECRET_KEY = sk_test_xxxxx  (server-only - never expose this
      one client-side or commit it to git)
  Without a secret key, /api/verify-payment falls back to a dev-only
  simulated success (already existed before this fix, unchanged) - real
  end-to-end verification against Paystack needs both keys set.

  Run from the ROOT of your local repo clone:
      powershell -ExecutionPolicy Bypass -File .\Fix-PaystackFullyWired.ps1
#>

$ErrorActionPreference = "Stop"
$root = Get-Location
$backupDir = Join-Path $root ".fix-backup-batch6-paystack"
if (-not (Test-Path -LiteralPath $backupDir)) { New-Item -ItemType Directory -Path $backupDir | Out-Null }

function Get-FullPath($rel) { return Join-Path $root $rel }

function Backup-Path($full) {
    if (Test-Path -LiteralPath $full) {
        $rel = $full.Substring($root.Path.Length).TrimStart('\','/')
        $dest = Join-Path $backupDir $rel
        $destParent = Split-Path $dest -Parent
        if (-not (Test-Path -LiteralPath $destParent)) { New-Item -ItemType Directory -Path $destParent -Force | Out-Null }
        Copy-Item -LiteralPath $full -Destination $dest -Force
    }
}

function Write-FullFile($relPath, $base64Content, $label) {
    $full = Get-FullPath $relPath
    if (-not (Test-Path -LiteralPath $full)) {
        Write-Host "  SKIP (not found): $relPath - is this the right repo root?" -ForegroundColor Yellow
        return
    }
    Backup-Path $full
    $bytes = [System.Convert]::FromBase64String($base64Content)
    [System.IO.File]::WriteAllBytes($full, $bytes)
    Write-Host "  REPLACED: $label" -ForegroundColor Green
}

