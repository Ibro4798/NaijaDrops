<#
  Add-SmartLocationSearch.ps1
  Compatible with Windows PowerShell 5.1 (no PS7-only syntax used).

  Adds an AI-assisted fallback for local place-name search, plus wires it
  into both search screens. Unlike the previous Fix-*.ps1 scripts, this one
  ADDS a brand new file (the API route) in addition to replacing two
  existing ones - same backed-up, byte-for-byte approach otherwise.

  THE IDEA: Mapbox's geocoding index for Kano is real but thin, especially
  for informal/colloquial local names (e.g. "Brigade" for Brigade Market,
  near the 3 Brigade Nigerian Army barracks). Switching to Google Places
  entirely would need you to set up a Google Cloud billing account and API
  key just to test this. Instead: this reuses the ANTHROPIC_API_KEY this
  app ALREADY has configured (see /api/estimate-package) for a narrow,
  low-risk job - Claude never supplies coordinates itself. It only ever
  proposes a fuller, more complete version of what was typed (e.g.
  "brigade" -> "Brigade Market, Sabon Gari, Kano, Nigeria"), grounded in its
  general knowledge of well-known local places. That proposed text is then
  sent to the REAL geocoder (Mapbox) to resolve to an actual, authoritative
  coordinate. If Mapbox can't find a match for what Claude proposed, nothing
  is returned - it never falls back to trusting a model-guessed lat/lng
  directly, since that risks confidently sending a rider to the wrong place.

  This only runs when the direct Mapbox search already came up completely
  empty (checked in both send-package/step-1 and vendor/create-delivery),
  so it adds latency/cost only on searches that were already failing
  outright - never on every keystroke. Results that come through this path
  show a small green "AI Match" badge in both suggestion dropdowns so it's
  transparent where they came from.

  REQUIRES: ANTHROPIC_API_KEY set in your environment (same one used by
  /api/estimate-package - if that feature already works for you, this one
  will too with no extra setup). If it's missing, this fallback silently
  does nothing and search behaves exactly as before - it never breaks the
  primary Mapbox search.

  Run from the ROOT of your local repo clone:
      powershell -ExecutionPolicy Bypass -File .\Add-SmartLocationSearch.ps1
#>

$ErrorActionPreference = "Stop"
$root = Get-Location
$backupDir = Join-Path $root ".fix-backup-batch5-smartsearch"
if (-not (Test-Path -LiteralPath $backupDir)) { New-Item -ItemType Directory -Path $backupDir | Out-Null }

function Get-FullPath($rel) { return Join-Path $root $rel }

function Backup-Path($full) {
    if (Test-Path -LiteralPath $full) {
        $rel = $full.Substring($root.Path.Length).TrimStart('\','/')
        $dest = Join-Path $backupDir $rel
        $destParent = Split-Path $dest -Parent
        if (-not (Test-Path -LiteralPath $destParent)) { New-Item -ItemType Directory -Path $destParent -Force | Out-Null }
        Copy-Item -LiteralPath $full -Destination $dest -Force
    }
}

function Write-FullFile($relPath, $base64Content, $label) {
    $full = Get-FullPath $relPath
    if (-not (Test-Path -LiteralPath $full)) {
        Write-Host "  SKIP (not found): $relPath - is this the right repo root?" -ForegroundColor Yellow
        return
    }
    Backup-Path $full
    $bytes = [System.Convert]::FromBase64String($base64Content)
    [System.IO.File]::WriteAllBytes($full, $bytes)
    Write-Host "  REPLACED: $label" -ForegroundColor Green
}

function Write-NewFile($relPath, $base64Content, $label) {
    $full = Get-FullPath $relPath
    $existed = Test-Path -LiteralPath $full
    if ($existed) { Backup-Path $full }
    $parent = Split-Path $full -Parent
    if (-not (Test-Path -LiteralPath $parent)) { New-Item -ItemType Directory -Path $parent -Force | Out-Null }
    $bytes = [System.Convert]::FromBase64String($base64Content)
    [System.IO.File]::WriteAllBytes($full, $bytes)
    if ($existed) {
        Write-Host "  REPLACED (already existed): $label" -ForegroundColor Green
    } else {
        Write-Host "  CREATED: $label" -ForegroundColor Green
    }
}

if (-not (Test-Path -LiteralPath (Get-FullPath "src\app"))) {
    Write-Host "ERROR: src\app not found. Run this script from the repo root." -ForegroundColor Red
    exit 1
}

