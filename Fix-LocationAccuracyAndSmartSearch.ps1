<#
  Fix-LocationAccuracyAndSmartSearch.ps1
  Compatible with Windows PowerShell 5.1 (no PS7-only syntax used).

  Full, backed-up REPLACEMENT of the 4 files below - same approach as the
  previous Fix-*.ps1 scripts. Each file's exact new content is embedded as
  base64 of the RAW ORIGINAL BYTES (BOM included, since all 4 files already
  had one) and written back byte-for-byte with no text re-encoding step.

  What this fixes:

  1. "USE MY LOCATION" WAS TOTALLY INACCURATE
     Found two compounding bugs in src\utils\geolocation.js:
       - GPS was only given a flat 2.5 seconds to converge before the code
         gave up and fell back to IP-based location. Real GPS chips
         (especially a "cold start") routinely take 5-15+ seconds to lock
         on - 2.5s meant almost every call fell through to the fallback
         instead of ever letting GPS actually work.
       - The fallback logic then explicitly PREFERRED that IP-based location
         over a real GPS reading unless the GPS reading's accuracy was under
         an unreasonably tight 200m. IP geolocation (via ipapi.co here) is
         hardcoded to a flat 5000m/5km accuracy figure and can be wildly off
         depending on the user's ISP - a 300m or even 800m GPS reading is
         virtually always closer to the truth, but the old code threw it
         away in exactly that situation.
     Fixed: GPS now gets a real 9-second budget to converge (resolving
     instantly on a genuinely good reading), and once time is up, whichever
     of {best GPS reading, IP location} has the smaller/better accuracy
     value wins - not a fixed preference either way. IP is now a true last
     resort, only used when GPS produced nothing at all.

  2. SMART LOCATION SEARCH ("GOOGLE MAPS-LIKE" KNOWLEDGE)
     src\utils\mapbox.js was passing a very tight hard bbox restriction to
     Mapbox's Geocoding API - anything outside a small box around central
     Kano returned zero results at all, even real landmarks in surrounding
     suburbs/LGAs. Widened to a Greater Kano metro bounding box (~40-50km
     buffer instead of just the city core), and added:
       - `proximity` biasing so results near wherever the user is
         searching from rank higher first, the way Google Maps does,
         without excluding farther matches entirely
       - explicit `types` (poi, address, neighborhood, locality, place,
         district) so points of interest and landmarks are properly
         represented, not just streets/addresses
     Both send-package/step-1 and vendor/create-delivery now pass the
     current map location through as that proximity bias. Also expanded
     vendor/create-delivery's tiny 5-item hardcoded landmark list (used for
     instant, no-network-latency suggestions) to 17 genuinely well-known
     Kano landmarks - markets, hospitals, the airport, GRAs, etc.

  Run from the ROOT of your local repo clone:
      powershell -ExecutionPolicy Bypass -File .\Fix-LocationAccuracyAndSmartSearch.ps1
#>

$ErrorActionPreference = "Stop"
$root = Get-Location
$backupDir = Join-Path $root ".fix-backup-batch4"
if (-not (Test-Path -LiteralPath $backupDir)) { New-Item -ItemType Directory -Path $backupDir | Out-Null }

function Get-FullPath($rel) { return Join-Path $root $rel }

function Backup-Path($full) {
    if (Test-Path -LiteralPath $full) {
        $rel = $full.Substring($root.Path.Length).TrimStart('\','/')
        $dest = Join-Path $backupDir $rel
        $destParent = Split-Path $dest -Parent
        if (-not (Test-Path -LiteralPath $destParent)) { New-Item -ItemType Directory -Path $destParent -Force | Out-Null }
        Copy-Item -LiteralPath $full -Destination $dest -Force
    }
}

function Write-FullFile($relPath, $base64Content, $label) {
    $full = Get-FullPath $relPath
    if (-not (Test-Path -LiteralPath $full)) {
        Write-Host "  SKIP (not found): $relPath - is this the right repo root?" -ForegroundColor Yellow
        return
    }
    Backup-Path $full
    $bytes = [System.Convert]::FromBase64String($base64Content)
    [System.IO.File]::WriteAllBytes($full, $bytes)
    Write-Host "  REPLACED: $label" -ForegroundColor Green
}

