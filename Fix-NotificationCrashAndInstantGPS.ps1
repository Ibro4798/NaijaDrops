<#
  Fix-NotificationCrashAndInstantGPS.ps1
  Compatible with Windows PowerShell 5.1 (no PS7-only syntax used).

  Full, backed-up REPLACEMENT of 2 files + 1 NEW file, same approach as
  previous Fix-*.ps1 scripts. Each file's exact content is embedded as
  base64 of the RAW FILE BYTES and written back byte-for-byte.

  ISSUE 1 - THE "Something went wrong" CRASH (from the screenshot):

  Root cause: src/app/layout.js renders ClientNotificationListeners as a
  SIBLING of {children}, not a descendant of it. That placement matters -
  app/error.jsx only catches errors thrown inside the routed page tree
  ({children}); it can't see errors from things rendered alongside it in
  the layout. ClientNotificationListeners wraps two next/dynamic(...,
  { ssr: false }) imports (ChatNotificationListener,
  OrderStatusNotificationListener). If either one's JS chunk fails to load
  - a stale tab from before a deploy, or a flaky/slow connection (the
  screenshot shows "68.7 K/s" and weak signal bars) - the render-time
  throw skips straight past app/error.jsx and hits app/global-error.jsx
  instead, crashing the ENTIRE app over the failure of two nonessential
  toast-notification listeners. ChunkErrorRecovery.jsx's window.onerror
  listener doesn't catch this either, because React's error-boundary
  mechanism intercepts a render-phase throw internally, before it can ever
  become an uncaught global error event.

  Fix: a new SilentErrorBoundary.jsx (a minimal class component - React
  error boundaries still require the class lifecycle) wraps each of the
  two listeners individually inside ClientNotificationListeners.jsx. If
  either listener's chunk fails, that one listener silently goes dark for
  the rest of the session - nothing else in the app is affected, no crash
  screen, no lost navigation/forms/checkout.

  ISSUE 2 - GPS BLOCKING THE "Continue" BUTTON ON send-package/step-1:

  Previously "Use My Location" awaited getReliableLocation() to fully
  settle (up to 32s on a slow connection) before the customer could reach
  step 2, even though the FIRST usable reading is almost always good
  enough. Now the first reading immediately reverse-geocodes, sets pickup,
  and clears the spinner - Continue is reachable right away. The
  underlying GPS watch keeps running in the background exactly as before;
  any better fix that arrives afterward silently tightens pickup's
  lat/lng (no re-geocode, no status text, no visible change) whether the
  customer is still on step 1 or has already moved on to step 2. An
  isMountedRef guard stops the background refinement from touching state
  after the component has unmounted.

  Run from the ROOT of your local repo clone:
      powershell -ExecutionPolicy Bypass -File .\Fix-NotificationCrashAndInstantGPS.ps1
