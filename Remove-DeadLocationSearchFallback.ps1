<#
  Remove-DeadLocationSearchFallback.ps1
  Compatible with Windows PowerShell 5.1 (no PS7-only syntax used).

  Full, backed-up REPLACEMENT of 3 files, plus DELETION of one now-unused
  API route directory. Each replaced file's exact content is embedded as
  base64 of the RAW FILE BYTES and written back byte-for-byte.

  WHAT THIS REMOVES AND WHY:

  getMapboxSuggestions() (src/utils/mapbox.js) already merges Mapbox +
  Nominatim + Photon results internally. All three call sites -
  send-package/step-1, MapModal.jsx, and vendor/create-delivery - ALSO had
  a fallback that, on an empty result, called /api/smart-location-search,
  which queries the exact same Nominatim + Photon APIs with the exact same
  query string. That fallback could never surface anything the first call
  didn't already try - it was a guaranteed-empty retry, not a genuinely
  different search strategy. Removed from all three call sites as dead
  weight; the /api/smart-location-search route itself is deleted since
  nothing calls it anymore.

  If a name like "Brigade" still doesn't resolve after this, that's a gap
  in OpenStreetMap's coverage for that specific name in Kano - not a
  wiring bug. The real fix for that (a small curated alias table mapping
  known local names to coordinates you supply) is a separate, deliberate
  feature to build if/when it's worth it - not part of this cleanup.

  ALSO FIXED (found while removing the above): the "Web Match" badge in
  all three files was checking flags (isAI, source === "web-search") that
  ONLY the now-removed fallback ever set - meaning the badge was already
  permanently dark even before this change, never once rendering for a
  real result. The OSM-merged results (Nominatim/Photon) are actually
  tagged `isOSM` by getMapboxSuggestions() itself. All three badges now
  key off `isOSM` instead, so a genuine non-Mapbox web match is correctly
  labeled again. (vendor/create-delivery's search also reshapes the
  suggestion object before rendering it - that reshape now carries `isOSM`
  through instead of silently dropping it.)

  Run from the ROOT of your local repo clone:
      powershell -ExecutionPolicy Bypass -File .\Remove-DeadLocationSearchFallback.ps1
#>

$ErrorActionPreference = "Stop"
$root = Get-Location
$backupDir = Join-Path $root ".fix-backup-deadsearch"
if (-not (Test-Path -LiteralPath $backupDir)) { New-Item -ItemType Directory -Path $backupDir | Out-Null }

function Get-FullPath($rel) { return Join-Path $root $rel }

function Backup-Path($full) {
    if (Test-Path -LiteralPath $full) {
        $rel = $full.Substring($root.Path.Length).TrimStart('\','/')
        $dest = Join-Path $backupDir $rel
        $destParent = Split-Path $dest -Parent
        if (-not (Test-Path -LiteralPath $destParent)) { New-Item -ItemType Directory -Path $destParent -Force | Out-Null }
        Copy-Item -LiteralPath $full -Destination $dest -Recurse -Force
    }
}

function Write-FullFile($relPath, $base64Content, $label) {
    $full = Get-FullPath $relPath
    if (-not (Test-Path -LiteralPath $full)) {
        Write-Host "  SKIP (not found): $relPath - is this the right repo root?" -ForegroundColor Yellow
        return
    }
    Backup-Path $full
    $bytes = [System.Convert]::FromBase64String($base64Content)
    [System.IO.File]::WriteAllBytes($full, $bytes)
    Write-Host "  REPLACED: $label" -ForegroundColor Green
}

if (-not (Test-Path -LiteralPath (Get-FullPath "src\app"))) {
    Write-Host "ERROR: src\app not found. Run this script from the repo root." -ForegroundColor Red
    exit 1
}

