<#
  Fix-TrackingRoleAndGPSCancel.ps1
  Compatible with Windows PowerShell 5.1 (no PS7-only syntax used).

  Full, backed-up REPLACEMENT of 3 files. Each file's exact content is
  embedded as base64 of the RAW FILE BYTES and written back byte-for-byte.

  ISSUE 1 - SECURITY BUG: SHARED TRACKING LINK EXPOSED VENDOR CONTROLS

  src/app/tracking/[orderId]/page.jsx set isVendorView = true for ANY
  authenticated user whose read of the order succeeded via RLS - but the
  "Vendor, assigned rider, broadcast rider, or admin can view order" RLS
  policy on orders (confirmed directly in Supabase) also legitimately lets
  a RIDER who was simply offered the job read that row, even one who lost
  the bid. The code never checked WHICH of those it actually was. Result:
  a rider opening the shared tracking link got the full vendor management
  view - other riders' bid amounts, and a "Cancel Order" button for a
  delivery that isn't theirs to cancel.

  Fixed: viewerRole is now computed by an actual ownership comparison
  (fetching the viewer's own vendor/rider row and comparing IDs against
  the order's vendor_id/rider_id) rather than trusting "a row came back."
  It's a real three-way value now - 'vendor' | 'rider' | 'customer' -
  instead of the old binary isVendorView flag (kept as a derived boolean
  for the existing UI checks, but now backed by real identity).

  ISSUE 2 - "3-WAY COMMUNICATION" (same root cause as issue 1)

  Because viewerRole was only ever vendor-or-not, a genuinely authenticated
  rider had currentUserId forced to null in chat (their own messages
  couldn't be attributed to them), and the "message" button always opened
  the vendor<->customer channel regardless of who was actually messaging.
  Fixed alongside issue 1: currentUserId is now set whenever authenticated
  (vendor OR rider), and the message button opens vendor_rider or
  vendor_customer based on the real viewerRole.

  ISSUE 3 - GPS: RE-ADDED FIRST-FIX UNBLOCK, THIS TIME WITH THE ACCURACY
  FLOOR, PLUS A CANCEL BUTTON

  Re-implements "unblock on first fix, keep refining in the background" in
  send-package/step-1 - but gated on geolocation.js's `usable` flag
  (accuracy <=150m, or 8s elapsed with nothing better) this time, which is
  what was missing when this shipped before and caused the regression that
  led to reverting it. A rougher reading still pans the live map for
  visual feedback but is never committed as the actual pickup point.

  Also adds real cancellation: getReliableLocation() now accepts an
  AbortSignal (2nd arg, { signal }) and resolves immediately with whatever
  reading is known so far if aborted - a visible Cancel button next to the
  GPS spinner on send-package/step-1 wires this up, so a customer isn't
  stuck waiting out the full 15-32s timeout with no way out.

  Run from the ROOT of your local repo clone:
      powershell -ExecutionPolicy Bypass -File .\Fix-TrackingRoleAndGPSCancel.ps1
#>

$ErrorActionPreference = "Stop"
$root = Get-Location
$backupDir = Join-Path $root ".fix-backup-trackingrole"
if (-not (Test-Path -LiteralPath $backupDir)) { New-Item -ItemType Directory -Path $backupDir | Out-Null }

function Get-FullPath($rel) { return Join-Path $root $rel }

function Backup-Path($full) {
    if (Test-Path -LiteralPath $full) {
        $rel = $full.Substring($root.Path.Length).TrimStart('\','/')
        $dest = Join-Path $backupDir $rel
        $destParent = Split-Path $dest -Parent
        if (-not (Test-Path -LiteralPath $destParent)) { New-Item -ItemType Directory -Path $destParent -Force | Out-Null }
        Copy-Item -LiteralPath $full -Destination $dest -Force
    }
}

function Write-FullFile($relPath, $base64Content, $label) {
    $full = Get-FullPath $relPath
    if (-not (Test-Path -LiteralPath $full)) {
        Write-Host "  SKIP (not found): $relPath - is this the right repo root?" -ForegroundColor Yellow
        return
    }
    Backup-Path $full
    $bytes = [System.Convert]::FromBase64String($base64Content)
    [System.IO.File]::WriteAllBytes($full, $bytes)
    Write-Host "  REPLACED: $label" -ForegroundColor Green
}

